"""Quem toca o som de fato: a mesma interface de frontend/src/motor/reprodutor.ts.

O Motor decide O QUE tocar; o Reprodutor só obedece. As chamadas do
OuvinteReprodutor têm que chegar na thread do Motor (o loop do servidor):
reprodutor que roda em outra thread usa `agendar` pra isso.
"""

from __future__ import annotations

from typing import Protocol


class OuvinteReprodutor(Protocol):
    def tocando(self) -> None: ...
    def pausado(self) -> None: ...
    def fim(self) -> None: ...
    def erro(self, motivo: str) -> None: ...
    def titulo(self, titulo: str) -> None:
        """O título de verdade do vídeo, quando o reprodutor descobre."""


class Reprodutor(Protocol):
    def ouvir(self, ouvinte: OuvinteReprodutor) -> None: ...
    def carregar(self, link: str) -> None: ...
    def tocar(self) -> None: ...
    def pausar(self) -> None: ...
    def parar(self) -> None: ...
    def buscar(self, segundos: float) -> None: ...
    def definir_volume(self, volume: int) -> None: ...  # 0-100
    def posicao(self) -> float: ...
    def duracao(self) -> float: ...
